#!/bin/bash
# Regenerate MEGAcmd launchers in ~/.local/bin (rootless install).
# The shipped binaries have RUNPATH=/opt/megacmd/lib hardcoded, which we cannot
# create without root, so every command gets a thin wrapper that points the
# dynamic linker at the extracted bundles instead.
set -euo pipefail

BASE="${MEGACMD_PREFIX:-$HOME/.local/megacmd}"
SRC="$BASE/root/usr/bin"
BINDIR="${MEGACMD_BINDIR:-$HOME/.local/bin}"
LIBDIR="$BASE/root/opt/megacmd/lib:$BASE/libs"

[ -d "$SRC" ] || { echo "missing $SRC" >&2; exit 1; }
mkdir -p "$BINDIR"

count=0
for f in "$SRC"/mega-*; do
    name="$(basename "$f")"
    out="$BINDIR/$name"
    # never clobber a real (non-MEGAcmd) file we did not create
    if [ -e "$out" ] && ! grep -qs 'MEGAcmd rootless launcher' "$out"; then
        echo "skip (foreign file): $out" >&2
        continue
    fi
    cat > "$out" <<EOF
#!/bin/bash
# MEGAcmd rootless launcher - generated by $BASE/setup-launchers.sh
export LD_LIBRARY_PATH="$LIBDIR\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
exec "$f" "\$@"
EOF
    chmod 755 "$out"
    count=$((count + 1))
done

echo "generated $count launchers in $BINDIR"
